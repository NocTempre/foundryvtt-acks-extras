/**
 * Writes the developer reference into `reference/` at the module root: the
 * module map and one API page per `acksExtras` key, read from `scripts/` as
 * it stands. The folder is build output, gitignored and shipped in the zip,
 * the same footing as the compiled packs.
 *
 * The pages are the ones the site publishes (`docs/site/tools/sync.mjs`
 * stages the same render), with links spelled as paths inside the module
 * directory. The folder is emptied first, so a page for a key that no longer
 * exists cannot outlive it.
 *
 *   node tools/build-reference.mjs           write reference/
 *   node tools/build-reference.mjs --check   render and report; write nothing
 *
 * Exits non-zero, writing nothing, when an import names no file or a key of
 * the namespace cannot be followed to a declaration.
 */
import fs from "node:fs";
import path from "node:path";

import { renderReference } from "../docs/site/tools/render-reference.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "reference");
const CHECK_ONLY = process.argv.includes("--check");

const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "module.json"), "utf8"));

/** Links from a page at `depth` folders below `reference/`. */
const up = (depth) => "../".repeat(depth + 1);
const linksFor = (depth) => ({
  source: (file, line) => `${up(depth)}${file}${line ? `#L${line}` : ""}`,
  map: (dir) => `${"../".repeat(depth)}architecture.md#${dir}`,
  api: (feature) => `api/${feature}.md`,
  fromIndex: (feature) => `${feature}.md`,
});

// A page's own depth decides how its links climb, so the render runs once per
// depth and each page is taken from the run that matches where it lands.
const byDepth = [renderReference(linksFor(0)), renderReference(linksFor(1))];
const { problems, counts } = byDepth[0];

if (problems.length) {
  for (const p of problems) console.error(`build-reference: ${p}`);
  console.error(`build-reference: ${problems.length} problem(s); nothing written.`);
  process.exit(1);
}

const header = `<!-- GENERATED by tools/build-reference.mjs from scripts/ at ${manifest.id} ${manifest.version}. Rebuilt by every release; edits here are overwritten. -->`;

if (!CHECK_ONLY) {
  fs.rmSync(OUT, { recursive: true, force: true });
  for (const page of byDepth[0].pages) {
    const depth = page.path.split("/").length - 1;
    const body = byDepth[depth].pages.find((p) => p.path === page.path).body;
    const file = path.join(OUT, `${page.path}.md`);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `${header}\n\n# ${page.title}\n\n${body.trimEnd()}\n`);
  }
}

console.log(
  `build-reference: ${CHECK_ONLY ? "checked" : "wrote"} ${byDepth[0].pages.length} pages — ${counts.files} files, ${counts.imports} imports, ` +
    `${counts.keys} keys (${counts.undocumented} functions without a docstring)`,
);
