/**
 * Stages repo content into the Astro tree.
 *
 * Everything written here is a COPY with a generated header saying so. The
 * originals — `docs/guides/`, `docs/releases/`, `docs/GALLERY.md` and
 * `vendor/acks-design/` — stay the only place their content is authored, which
 * is what keeps the site from becoming the second place a fact is stated. The
 * staged paths are gitignored for the same reason.
 */
import fs from "node:fs";
import path from "node:path";

import { REPO } from "./parse.mjs";

const SITE = path.resolve(import.meta.dirname, "..");

const GENERATED = (source) =>
  `<!-- GENERATED by docs/site/tools/sync.mjs from ${source}. Do not edit: run \`npm run sync\` in docs/site/. -->`;

/** "Edit this page" target for a staged page: the real source, not the copy. */
const EDIT_URL = (repoPath) => `https://github.com/NocTempre/foundryvtt-acks-extras/edit/main/${repoPath}`;

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function copyDir(from, to) {
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
}

/** YAML-safe double-quoted scalar. */
const yaml = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

/** Markdown/HTML stripped to a single line of prose. */
function plain(md) {
  return md
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[*_`>#]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Copy the design system in, re-pointing its dark branch at Starlight's switch.
 *
 * The tokens file keys dark on an `:is(.theme-dark, [data-acks-theme="dark"])`
 * list (Foundry's class and its own preview harness) wrapped in the two
 * forced-light `:not()` guards; Starlight stamps `data-theme="dark"` on
 * `<html>`. Adding `:root[data-theme="dark"]` inside the `:is()` list — guards
 * intact — is what lets the palette stay authored once; the alternative,
 * re-declaring the dark values here, is exactly the duplication the tokens
 * file's own header warns against.
 */
function stageDesignSystem() {
  const from = path.join(REPO, "vendor", "acks-design");
  const to = path.join(SITE, "src", "styles", "vendor");

  copyDir(path.join(from, "fonts"), path.join(to, "fonts"));

  const tokens = fs.readFileSync(path.join(from, "tokens.css"), "utf8");
  const marker =
    ':is(.theme-dark, [data-acks-theme="dark"]):not([data-acks-theme="light"]):not([data-acks-theme="light"] *) {';
  if (!tokens.includes(marker)) {
    throw new Error(
      "vendor/acks-design/tokens.css no longer opens its dark block with the expected selector list; " +
        "update stageDesignSystem() in docs/site/tools/stage-content.mjs to match.",
    );
  }
  const patched = tokens.replace(
    marker,
    ':is(.theme-dark, [data-acks-theme="dark"], :root[data-theme="dark"]):not([data-acks-theme="light"]):not([data-acks-theme="light"] *) {',
  );
  write(
    path.join(to, "tokens.css"),
    `/* GENERATED from vendor/acks-design/tokens.css — the dark selector list gains\n` +
      ` * :root[data-theme="dark"] so Starlight's theme switch drives the ACKS palette.\n` +
      ` * Do not edit: run \`npm run sync\` in docs/site/. */\n${patched}`,
  );
}

/**
 * Guides, verbatim apart from frontmatter and image paths.
 *
 * Starlight renders the frontmatter title as the page heading, so the source
 * `# Heading` is lifted out rather than left to render twice. Screenshot
 * references move from `../releases/` to the staged asset tree, where Astro can
 * optimize them and prefix the site base; the italic caption each guide already
 * writes under its images becomes the alt text, which the source leaves empty.
 */
function stageGuides() {
  const from = path.join(REPO, "docs", "guides");
  const to = path.join(SITE, "src", "content", "docs", "guides");
  fs.rmSync(to, { recursive: true, force: true });

  const staged = [];
  for (const file of fs.readdirSync(from).filter((f) => f.endsWith(".md"))) {
    const slug = file.replace(/\.md$/, "");
    const src = fs.readFileSync(path.join(from, file), "utf8");

    const title = src.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? slug;
    let body = src.replace(/^#\s+.+$/m, "").trimStart();

    const lead = body.split(/\n\s*\n/).find((p) => p.trim() && !p.trimStart().startsWith("!["));
    const description = plain(lead ?? title).slice(0, 300);

    // `![](../releases/v1.3.0/shot.png)` -> the staged asset, with the caption
    // that follows lifted into alt text.
    // The caption is matched across line breaks on purpose: the guides wrap
    // theirs to the same column as the prose, so a line-bounded match reads
    // alt text off the short captions only and silently leaves the rest empty.
    body = body.replace(
      /!\[([^\]]*)\]\(\.\.\/releases\/([^)]+)\)(\s*\n\s*\n\*([^*]+?)\*)?/g,
      (_whole, alt, rel, captionBlock, caption) => {
        const text = (alt || caption || "")
          .replace(/[[\]]/g, "")
          .replace(/\s+/g, " ")
          .trim()
          .slice(0, 220);
        return `![${text}](../../../assets/shots/${rel})${captionBlock ?? ""}`;
      },
    );

    const frontmatter = [
      "---",
      `title: ${yaml(title)}`,
      `description: ${yaml(description)}`,
      `editUrl: ${yaml(EDIT_URL(`docs/guides/${file}`))}`,
      "---",
      "",
      GENERATED(`docs/guides/${file}`),
      "",
    ].join("\n");

    write(path.join(to, file), frontmatter + body.trimEnd() + "\n");
    staged.push({ slug, title, description });
  }
  return staged;
}

/** Release screenshots, as an Astro asset tree so they are optimized and hashed. */
function stageScreenshots() {
  copyDir(path.join(REPO, "docs", "releases"), path.join(SITE, "src", "assets", "shots"));
}

/**
 * The gallery index, parsed out of the table in `docs/GALLERY.md`.
 *
 * That table is already the repo's per-feature index of "what it shows, which
 * guide explains it, which release the shot came from", and it is maintained as
 * part of every release. Reading it keeps the site's gallery and the repo's
 * gallery the same list rather than two lists that agree until they don't.
 */
function stageGallery() {
  const md = fs.readFileSync(path.join(REPO, "docs", "GALLERY.md"), "utf8");
  const rows = [];

  for (const line of md.split("\n")) {
    if (!line.startsWith("|") || /^\|\s*-+/.test(line) || /\|\s*Feature\s*\|/.test(line)) continue;
    const cells = line.split("|").slice(1, -1).map((c) => c.trim());
    if (cells.length < 4) continue;

    const [feature, shows, guideCell, shotCell] = cells;
    const guide = guideCell.match(/\]\(guides\/([^)#]+)\.md(#[^)]*)?\)/);
    const shot = shotCell.match(/\]\(releases\/([^)]+)\)/);
    if (!guide || !shot) continue;

    rows.push({
      feature,
      shows,
      guide: guide[1],
      anchor: guide[2] ?? "",
      shot: shot[1],
      release: shot[1].split("/")[0],
    });
  }

  if (!rows.length) throw new Error("docs/GALLERY.md yielded no rows — has its table shape changed?");
  write(path.join(SITE, "src", "data", "gallery.json"), JSON.stringify(rows, null, 2) + "\n");
  return rows;
}

/**
 * Split the root README into its `##` sections.
 *
 * The README is the module's front door on GitHub and in the Foundry package
 * listing, and it already says what the module is, how to install it and how to
 * start. The site publishes those sections rather than a second retelling that
 * agrees with the README until one of them is edited.
 *
 * @returns {Map<string, string>} heading text to section body, headings demoted
 *   one level so the section's own `##` can become the page title
 */
function readmeSections() {
  const md = fs.readFileSync(path.join(REPO, "README.md"), "utf8");
  const sections = new Map();

  const parts = md.split(/^## /m);
  sections.set(
    "__intro__",
    parts[0]
      .replace(/^#\s+.+$/m, "")
      // The README's banner link points readers AT this site; reprinting it on
      // a page of this site would send them in a circle.
      .replace(/^.*noctempre\.github\.io.*$/gim, "")
      .trim(),
  );

  for (const part of parts.slice(1)) {
    const newline = part.indexOf("\n");
    const heading = part.slice(0, newline).trim();
    const body = part
      .slice(newline + 1)
      // Horizontal rules separate sections on GitHub; on a page with one
      // section per route they are just a stray line.
      .replace(/^---\s*$/gm, "")
      // `###` subsections become the page's top level.
      .replace(/^####\s/gm, "### ")
      .replace(/^###\s/gm, "## ")
      .trim();
    sections.set(heading, body);
  }
  return sections;
}

/**
 * The three "start here" pages that restate nothing: each is a README section
 * with frontmatter, plus a line pointing at whatever the site does better.
 */
function stageStartPages() {
  const sections = readmeSections();
  const to = path.join(SITE, "src", "content", "docs", "start");

  const page = (file, title, description, body, lead = "") => {
    write(
      path.join(to, file),
      [
        "---",
        `title: ${yaml(title)}`,
        `description: ${yaml(description)}`,
        `editUrl: ${yaml(EDIT_URL("README.md"))}`,
        "---",
        "",
        GENERATED("README.md"),
        "",
        lead,
        body,
        "",
      ].join("\n"),
    );
  };

  const required = (heading) => {
    const body = sections.get(heading);
    if (!body) {
      throw new Error(`README.md no longer has a "## ${heading}" section — update stageStartPages().`);
    }
    return body;
  };

  page(
    "what-this-is.md",
    "What this is",
    "What ACKS II — Extras adds to Foundry VTT: the shared primitives and the seven feature areas built on them.",
    required("Features"),
    `${sections.get("__intro__")}\n\n:::tip\nSeeing is quicker than reading — the [feature gallery](../../gallery/) shows every one of these working.\n:::\n`,
  );

  page(
    "install.md",
    "Install",
    "Installing ACKS II — Extras in Foundry VTT: the manifest URL, what it requires, and upgrading from the eight separate modules.",
    required("Installation"),
    "",
  );

  page(
    "getting-started.md",
    "Getting started",
    "First steps after enabling ACKS II — Extras: the settings menu, the sample compendia, and where to go next.",
    required("Getting started"),
    "",
    );
}

export function stageContent() {
  stageDesignSystem();
  stageScreenshots();
  const guides = stageGuides();
  const gallery = stageGallery();
  stageStartPages();
  return { guides, gallery };
}

export { GENERATED, write };
